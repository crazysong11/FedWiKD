"""Generate paper Fig. 1 and Table I from completed experiment records."""

from pathlib import Path
import argparse
import json
import subprocess
import sys
from export_table import export_table

ROOT = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--data-root",
        type=Path,
        required=True,
        help="Results directory generated by the experiment entries; an explicit results_index.csv is optional.",
    )
    parser.add_argument("--output-dir", type=Path, default=ROOT / "outputs")
    args = parser.parse_args()
    data = args.data_root.resolve()
    output = args.output_dir.resolve()
    if not data.is_dir():
        parser.error("--data-root must be an existing results directory.")
    if output == data or data in output.parents:
        parser.error("--output-dir must be outside the original data directory.")
    result = subprocess.run(
        [
            sys.executable,
            "-B",
            "-X",
            "utf8",
            str(ROOT / "plot_final_results.py"),
            "--data-root",
            str(data),
            "--output-dir",
            str(output),
            "--smoothing-window",
            "5",
        ],
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if result.stderr:
        print(result.stderr, file=sys.stderr, end="")
    if result.returncode:
        print(result.stdout, end="")
        raise SystemExit(result.returncode)
    report = json.loads(result.stdout)
    rows = export_table(output / "final-results-statistics.json", output)
    print(
        f"Verified {report['records_verified']} runs; generated Fig. 1 and {len(rows)} Table I rows."
    )
    print(f"Output directory: {output}")


if __name__ == "__main__":
    main()
